                            <h3>Database Configured Successfully!</h3>
                            <p><strong>Configuration Used:</strong> ${data.config_name}</p>
                            <p><strong>Config File Updated:</strong> ${data.config_updated ? 'Yes' : 'No'}</p>
                            <p>Your database is now online and working perfectly!</p>
                            <a href="admin_dashboard.php" class="btn btn-success" style="margin-top: 15px;">Go to Admin Dashboard</a>
                        </div>
