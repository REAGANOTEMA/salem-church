// Test database configuration
function testDatabaseConfig($config) {
    try {
        $conn = new mysqli(
            $config['host'],
            $config['user'],
            $config['pass'],
            $config['name'],
            $config['port']
        );
        
        if ($conn->connect_error) {
            return [
                'success' => false,
                'error' => $conn->connect_error
            ];
        }
        
        // Test database access
        $queries = [
            "SELECT 1",
            "SHOW TABLES",
            "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = '" . $config['name'] . "'"
        ];
        
        foreach ($queries as $query) {
            $result = $conn->query($query);
            if (!$result) {
                $conn->close();
                return [
                    'success' => false,
                    'error' => 'Database query failed: ' . $query
                ];
            }
        }
        
        $conn->close();
        return [
            'success' => true,
            'message' => 'Connection successful!'
        ];
    } catch (Exception $e) {
        return [
            'success' => false,
            'error' => $e->getMessage()
        ];
    }
}

