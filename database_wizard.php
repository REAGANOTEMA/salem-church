// Auto-detect and configure database
function autoConfigureDatabase() {
    $results = [];
    
    // Test all possible configurations
    $configs = getAllDatabaseConfigs();
    
    foreach ($configs as $name => $config) {
        $result = testDatabaseConfig($config);
        $results[$name] = array_merge($result, ['config' => $config]);
        
        // If we find a working connection, stop testing
        if ($result['success']) {
            return [
                'success' => true,
                'working_config' => $config,
                'config_name' => $name,
                'all_results' => $results
            ];
        }
    }
    
    return [
        'success' => false,
        'working_config' => null,
        'all_results' => $results
    ];
}

